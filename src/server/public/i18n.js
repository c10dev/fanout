// Dashboard language: Korean (the source text) or English. Loaded before app.js.
//
// Strings in app.js and index.html are written in Korean and wrapped as tr('…'); the Korean text is
// the key, so a missing English entry falls back to Korean instead of showing an id. Placeholders
// look like {name} and are filled from the second argument. Messages that come from the server
// (platform errors, warnings) are not translated here.

const LANG_KEY = 'fanout.lang';

/** 'ko' or 'en': the saved choice, else the browser's language. */
const LANG = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
  } catch {
    // storage blocked: fall through to the browser language
  }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language ?? 'en'];
  return String(prefs[0] ?? 'en').toLowerCase().startsWith('ko') ? 'ko' : 'en';
})();

/** Locale for dates and numbers. */
const LOCALE = LANG === 'ko' ? 'ko-KR' : 'en-US';

/** Translate a Korean source string (see the note at the top). Named tr: app.js uses `t` for targets. */
function tr(key, vars) {
  const text = (LANG === 'en' && MESSAGES_EN[key]) || key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
}

function setLanguage(lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // not remembered; still switch for this page load
  }
  location.reload();
}

/** Translate the static page: text, placeholders, labels and titles marked with data-i18n*. */
function translateStatic(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = tr(el.dataset.i18n);
  for (const attr of ['placeholder', 'aria-label', 'title']) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, tr(el.getAttribute(`data-i18n-${attr}`)));
  }
}

